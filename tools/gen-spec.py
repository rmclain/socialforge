#!/usr/bin/env python3
"""Embed spec/platforms/*.json into the Mac app's Kit as Swift string literals.
Run after editing a spec: python3 tools/gen-spec.py"""
import pathlib
root = pathlib.Path(__file__).resolve().parent.parent
out = root / "apps/mac/Sources/SocialForgeKit/Generated/PlatformSpecData.swift"
out.parent.mkdir(parents=True, exist_ok=True)
lines = ["// GENERATED by tools/gen-spec.py from spec/platforms/*.json. Do not edit.", "",
         "enum PlatformSpecData {", "    static let json: [String: String] = ["]
for f in sorted((root / "spec/platforms").glob("*.json")):
    lines.append(f'        "{f.stem}": #"""\n{f.read_text().rstrip()}\n"""#,')
lines += ["    ]", "}", ""]
out.write_text("\n".join(lines))
print(f"wrote {out.relative_to(root)}")
